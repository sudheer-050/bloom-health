// Run: node check-vault.cjs. Uses only built-in Node modules.
const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const {webcrypto}=require('node:crypto');
const vault=require('./dist/vault.js');
async function check(){
  const data=vault.blank('Test person');
  data.days['2026-11-07']={water:750,weight:70,meals:[{id:'meal-one',name:'Private oats',meal:'Breakfast',calories:350,protein:12,carbs:54,fat:7}],activities:[{id:'activity-one',type:'Walk',minutes:20,note:'Private note'}]};
  const password='test-only passphrase 9!';
  const first=await vault.create('  FIRST@example.com ',password,data);
  assert.equal(first.record.email,'first@example.com');
  assert.equal(first.key.extractable,false);
  const serialized=JSON.stringify(first.record);
  assert(!serialized.includes('Private oats'));assert(!serialized.includes(password));assert(!serialized.includes('Test person'));
  const restored=await vault.unlock(vault.parse(serialized),password);
  assert.deepEqual(restored.data,data);
  await assert.rejects(vault.unlock(first.record,'incorrect password 9!'),/Could not unlock/);
  const tampered=structuredClone(first.record);tampered.email='other@example.com';
  await assert.rejects(vault.unlock(tampered,password),/Could not unlock/);
  const corrupted=structuredClone(first.record);corrupted.ciphertext=(corrupted.ciphertext[0]==='A'?'B':'A')+corrupted.ciphertext.slice(1);
  await assert.rejects(vault.unlock(corrupted,password),/Could not unlock/);
  const secondEncryption=await vault.seal(data,first.key,first.record);
  assert.notEqual(secondEncryption.iv,first.record.iv);
  assert.deepEqual((await vault.unlock(secondEncryption,password)).data,data);
  assert.throws(()=>vault.parse('{bad'),/not valid JSON/);
  assert.throws(()=>vault.parse(JSON.stringify({...first.record,iterations:1})),/supported/);
  const invalid=structuredClone(data);invalid.days['2026-11-07'].water=-1;
  assert.throws(()=>vault.journal(invalid),/water/);
  assert.throws(()=>vault.journal({...data,days:{'2026-02-30':data.days['2026-11-07']}}),/invalid date/);
  assert.throws(()=>vault.journal({...data,days:JSON.parse('{"__proto__":{}}')}),/invalid date/);
  const storage=new Map();
  let failWrites=false;
  const elements=new Map();
  const element=selector=>{if(!elements.has(selector))elements.set(selector,{addEventListener(){},setAttribute(){},replaceChildren(){},classList:{add(){},remove(){}},querySelector(){return element('submit');},close(){},showModal(){},hidden:false,dataset:{},textContent:'',innerHTML:''});return elements.get(selector);};
  const context=vm.createContext({BloomVault:vault,document:{querySelector:element,querySelectorAll:()=>[],addEventListener(){}},window:{addEventListener(){}},navigator:{locks:{request:async(key,fn)=>fn()}},localStorage:{getItem:key=>storage.get(key)??null,setItem:(key,value)=>{if(failWrites)throw new Error('Quota exceeded');storage.set(key,value);},removeItem:key=>storage.delete(key)},crypto:webcrypto,Date,setTimeout:()=>0,clearTimeout(){},console});
  vm.runInContext(readFileSync('dist/icons.js','utf8'),context);
  vm.runInContext(readFileSync('dist/app.js','utf8'),context);
  vm.runInContext(readFileSync('dist/landing.js','utf8'),context);
  vm.runInContext(readFileSync('dist/accounts.js','utf8'),context);
  assert.equal(elements.get('#landing-screen').hidden,false);
  assert.equal(elements.get('#auth-screen').hidden,true);
  assert.equal(storage.size,0,'Opening the landing page must not create or overwrite a journal.');
  context.fixture=data;context.active={...first,raw:serialized,dirty:false};
  const run=code=>vm.runInContext(code,context);
  run("state=fixture;date='2026-11-07';session=active");
  assert.equal(run("total('calories')"),350);assert.equal(run('minutes()'),20);
  assert.equal(run('percent(750,2000)'),38);assert.equal(run('percent(3000,2000)'),100);assert.equal(run('percent(-1,2000)'),0);
  assert.equal(run("esc('<script>')"),'&lt;script&gt;');
  run("date='2026-11-06'");assert.equal(run("total('calories')"),0);
  run('writableDay().water=250');assert.equal(data.days['2026-11-07'].water,750);
  storage.set(vault.storageKey(first.record.email),serialized);
  const other=await vault.create('second@example.com','another test passphrase',vault.blank('Other person'));
  const otherRaw=JSON.stringify(other.record);storage.set(vault.storageKey(other.record.email),otherRaw);
  assert.equal(await run('saveAccount()'),true);
  assert.equal(storage.get(vault.storageKey(other.record.email)),otherRaw);
  assert(!storage.get(vault.storageKey(first.record.email)).includes('Private oats'));
  const saved=storage.get(vault.storageKey(first.record.email));
  failWrites=true;run('state.days[date].water=500');
  assert.equal(await run('saveAccount()'),false);assert.equal(storage.get(vault.storageKey(first.record.email)),saved);assert.equal(run('session.dirty'),true);
  failWrites=false;storage.set(vault.storageKey(first.record.email),'changed by another tab');
  assert.equal(await run('saveAccount()'),false);assert.equal(storage.get(vault.storageKey(first.record.email)),'changed by another tab');
  storage.set(vault.storageKey(first.record.email),run('session.raw'));
  context.oldJournal=vault.blank('Old profile');context.oldJournal.goals.water=3200;
  run("state=BloomVault.blank('New profile');session.dirty=false;render=()=>{};previewLegacy(oldJournal)");
  await run("document.querySelector('#entry-form').onsubmit({preventDefault(){}})");
  assert.equal(run('state.goals.water'),3200);assert.equal(run('state.name'),'New profile');
  const accountBeforeGuest=storage.get(vault.storageKey(first.record.email));
  const guestData=vault.blank('Guest person');guestData.days['2026-11-07']={meals:[],activities:[],water:250,weight:null};
  storage.set('bloom-journal-v1',JSON.stringify(guestData));
  run('session=null');await run('startGuest()');
  assert.equal(run('session.guest'),true);assert.equal(run('state.days["2026-11-07"].water'),250);
  run('state.days["2026-11-07"].water=500');assert.equal(await run('saveAccount()'),true);
  run('session=null;state=BloomVault.blank()');await run('startGuest()');
  assert.equal(run('state.days["2026-11-07"].water'),500);
  assert.equal(storage.get(vault.storageKey(first.record.email)),accountBeforeGuest);
  assert.equal(storage.get(vault.storageKey(other.record.email)),otherRaw);
  const guestSaved=storage.get('bloom-journal-v1');failWrites=true;
  run('state.days["2026-11-07"].water=750');assert.equal(await run('saveAccount()'),false);
  assert.equal(storage.get('bloom-journal-v1'),guestSaved);assert.equal(run('session.dirty'),true);
  failWrites=false;storage.set('bloom-journal-v1','changed elsewhere');
  assert.equal(await run('saveAccount()'),false);assert.equal(storage.get('bloom-journal-v1'),'changed elsewhere');
  storage.set('bloom-journal-v1','malformed guest journal');run('session=null');await run('startGuest()');
  assert.equal(run('session'),null);assert.equal(storage.get('bloom-journal-v1'),'malformed guest journal');
  console.log('PASS: guest entry without credentials, saved-data reload, account isolation, failed writes, stale tabs and corrupt-data preservation.');
  console.log('PASS: encryption round-trip, wrong passwords, tampering, random IVs, invalid imports, account isolation, quota errors, concurrent edits, date isolation, and calculations.');
}
check().catch(error=>{console.error(error);process.exitCode=1;});
